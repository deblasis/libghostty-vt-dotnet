#!/usr/bin/env python3
"""Turn the generated P/Invoke reference into a compilable raw API layer.

ClangSharp writes several namespace blocks into one file. The first namespace
is left open until the end of the file, so the later blocks are nested
declarations with the same name and the `using` directives that start them
land after members. The reference is usable as a diff target but not as source.

This script collapses the redundant namespace wrappers into one file-scoped
namespace, hoists the late `using` directives, and rewrites the namespace and
class name so the result can be compiled as the public raw API.

Usage: build/emit-compiled-native.py <reference.cs> <output.cs>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

NAMESPACE = "Ghostty.Vt.Native"
OUTPUT_NAMESPACE = "Ghostty.Vt.Raw"
OUTPUT_CLASS = "GhosttyVtNative"


def fail(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(1)


def brace_delta(line: str) -> int:
    line = re.sub(r"//.*", "", line)
    line = re.sub(r'"(?:\\.|[^"\\])*"', '""', line)
    return line.count("{") - line.count("}")


def main() -> None:
    if len(sys.argv) != 3:
        fail("usage: emit-compiled-native.py <reference.cs> <output.cs>")

    reference = Path(sys.argv[1])
    output = Path(sys.argv[2])
    lines = reference.read_text(encoding="utf-8").splitlines()

    namespace_lines = [
        i
        for i, line in enumerate(lines)
        if line.strip() == f"namespace {NAMESPACE}"
    ]
    if len(namespace_lines) != 3:
        fail(
            f"expected 3 '{NAMESPACE}' blocks in {reference}, "
            f"found {len(namespace_lines)}"
        )

    text = "\n".join(lines)
    class_matches = re.findall(r"\bclass NativeMethods\b", text)
    if len(class_matches) != 1:
        fail("expected exactly one 'class NativeMethods' in the reference")
    dll_imports = text.count("DllImport(")
    native_imports = text.count('DllImport("libghostty-vt"')
    if dll_imports == 0 or native_imports != dll_imports:
        fail("reference contains DllImport declarations without the expected library")
    for rewritten in (
        "((ushort)(ansi) << 15)",
        "return ((mode >> 15) != 0) != 0;",
        "return mode & 0x7FFF;",
    ):
        if text.count(rewritten) != 1:
            fail(f"expected exactly one generated helper fragment: {rewritten!r}")

    blocks: list[tuple[int, int, int]] = []
    for ns in namespace_lines:
        open_line = ns + 1
        while open_line < len(lines) and not lines[open_line].strip():
            open_line += 1
        if open_line >= len(lines) or lines[open_line].strip() != "{":
            fail(f"namespace at line {ns + 1} is not followed by '{{'")

        depth = 0
        close_line = None
        for i in range(open_line, len(lines)):
            depth += brace_delta(lines[i])
            if depth == 0:
                close_line = i
                break
        if close_line is None:
            fail(f"could not find the closing brace for namespace at line {ns + 1}")
        blocks.append((ns, open_line, close_line))

    remove: set[int] = set()
    for index, (ns, open_line, close_line) in enumerate(blocks):
        remove.add(open_line)
        remove.add(close_line)
        if index:
            remove.add(ns)
        else:
            lines[ns] = f"namespace {OUTPUT_NAMESPACE};"

    # The late directives cannot stay after members in a file-scoped namespace.
    remove.update(
        i
        for i, line in enumerate(lines)
        if line.strip() in {"using System;", "using System.Diagnostics;"}
    )

    body = [line for i, line in enumerate(lines) if i not in remove]

    # Keep the directives the generated code needs at the file header.
    header = [
        "// <auto-generated>",
        "// Generated from build/bindings-reference/NativeMethods.pinned.cs by",
        "// build/emit-compiled-native.py. Do not edit by hand.",
        "// </auto-generated>",
        "using System;",
        "using System.Diagnostics;",
    ]
    body = [line for line in body if line.strip()]
    text = "\n".join(header + body) + "\n"

    text = re.sub(r"\bclass NativeMethods\b", f"class {OUTPUT_CLASS}", text)
    text = text.replace('DllImport("libghostty-vt"', 'DllImport("ghostty-vt"')

    # ClangSharp emits these inline macro helpers with C-style bool casts that
    # C# rejects. The values are correct; express the casts explicitly.
    text = text.replace(
        "((ushort)(ansi) << 15)", "((ushort)(ansi ? 1 : 0) << 15)"
    )
    text = text.replace("return ((mode >> 15) != 0) != 0;", "return (mode >> 15) != 0;")
    text = text.replace("return mode & 0x7FFF;", "return (ushort)(mode & 0x7FFF);")

    if not re.search(
        rf"(?m)^\s*public\s+static\s+unsafe\s+partial\s+class\s+{OUTPUT_CLASS}\b",
        text,
    ):
        fail(f"the raw entry-point class {OUTPUT_CLASS} must be public")

    output_namespaces = [
        line.strip() for line in text.splitlines() if line.startswith("namespace ")
    ]
    if output_namespaces != [f"namespace {OUTPUT_NAMESPACE};"]:
        fail(f"unexpected output namespace: {output_namespaces}")

    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
